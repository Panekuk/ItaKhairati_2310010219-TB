private void isiPegawai() {
    try {
        cbPegawai.removeAllItems();
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery("SELECT * FROM pegawai");

        while (rs.next()) {
            cbPegawai.addItem(
                rs.getInt("id_pegawai") + " - " + rs.getString("nama")
            );
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
}

private void tampilData() {
    model = new DefaultTableModel();
    model.addColumn("Nama");
    model.addColumn("Mulai");
    model.addColumn("Selesai");
    model.addColumn("Jenis");
    model.addColumn("Keterangan");

    try {
        String sql = "SELECT nama, tgl_mulai, tgl_selesai, jenis_cuti, keterangan " +
                     "FROM cuti c JOIN pegawai p ON c.id_pegawai=p.id_pegawai";
        ResultSet rs = conn.createStatement().executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString(1),
                rs.getString(2),
                rs.getString(3),
                rs.getString(4),
                rs.getString(5)
            });
        }
        tableCuti.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
}
