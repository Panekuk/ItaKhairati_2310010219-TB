    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
        String id = cbPegawai.getSelectedItem().toString().split(" - ")[0];

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String mulai = sdf.format(jMulai.getDate());
        String selesai = sdf.format(jSelesai.getDate());

        String sql = "INSERT INTO cuti VALUES (NULL,?,?,?,?,?)";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, Integer.parseInt(id));
        ps.setString(2, mulai);
        ps.setString(3, selesai);
        ps.setString(4, txtSelesai.getText()); // jenis cuti
        ps.setString(5, txtKeterangan.getText());

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data cuti berhasil disimpan");
        tampilData();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void tableCutiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableCutiMouseClicked
        int row = tableCuti.getSelectedRow();

    try {
        String nama = tableCuti.getValueAt(row, 0).toString();
        String mulai = tableCuti.getValueAt(row, 1).toString();
        String selesai = tableCuti.getValueAt(row, 2).toString();
        String jenis = tableCuti.getValueAt(row, 3).toString();
        String ket = tableCuti.getValueAt(row, 4).toString();

        // cari id_cuti
        String sql = "SELECT c.id_cuti, c.id_pegawai FROM cuti c " +
                     "JOIN pegawai p ON c.id_pegawai=p.id_pegawai " +
                     "WHERE p.nama=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, nama);
        ResultSet rs = ps.executeQuery();

        if (rs.next()) {
            idCuti = rs.getInt("id_cuti");
            int idPegawai = rs.getInt("id_pegawai");

            for (int i = 0; i < cbPegawai.getItemCount(); i++) {
                if (cbPegawai.getItemAt(i).startsWith(idPegawai + " -")) {
                    cbPegawai.setSelectedIndex(i);
                    break;
                }
            }
        }

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        jMulai.setDate(sdf.parse(mulai));
        jSelesai.setDate(sdf.parse(selesai));

        txtSelesai.setText(jenis);
        txtKeterangan.setText(ket);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    }//GEN-LAST:event_tableCutiMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
       if (idCuti == 0) {
        JOptionPane.showMessageDialog(this, "Pilih data dari tabel!");
        return;
    }

    try {
        String idPegawai = cbPegawai.getSelectedItem().toString().split(" - ")[0];
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        String sql = "UPDATE cuti SET id_pegawai=?, tgl_mulai=?, tgl_selesai=?, " +
                     "jenis_cuti=?, keterangan=? WHERE id_cuti=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, Integer.parseInt(idPegawai));
        ps.setString(2, sdf.format(jMulai.getDate()));
        ps.setString(3, sdf.format(jSelesai.getDate()));
        ps.setString(4, txtSelesai.getText());
        ps.setString(5, txtKeterangan.getText());
        ps.setInt(6, idCuti);

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data berhasil diupdate");

        tampilData();
        resetForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
      if (idCuti == 0) {
        JOptionPane.showMessageDialog(this, "Pilih data dari tabel!");
        return;
    }

    int konfirmasi = JOptionPane.showConfirmDialog(
        this,
        "Yakin hapus data ini?",
        "Konfirmasi",
        JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == JOptionPane.YES_OPTION) {
        try {
            String sql = "DELETE FROM cuti WHERE id_cuti=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idCuti);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
            tampilData();
            resetForm();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }
    }//GEN-LAST:event_btndeleteActionPerformed

