    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        DefaultTableModel model = new DefaultTableModel();
    model.addColumn("No"); model.addColumn("NIP"); model.addColumn("Nama");
    model.addColumn("Jabatan"); model.addColumn("Unit Kerja");
    
    String kolom = cbKategori.getSelectedItem().toString();
    if(kolom.equals("Unit")) kolom = "unit_kerja"; // Penyesuaian nama kolom DB
    
    try {
        int no = 1;
        String sql = "SELECT * FROM pegawai WHERE " + kolom + " LIKE '%" + txtSearch.getText() + "%'";
        Connection conn = Koneksi.getKoneksi();
        Statement stm = conn.createStatement();
        ResultSet res = stm.executeQuery(sql);
        while(res.next()){
            model.addRow(new Object[]{no++, res.getString("nip"), res.getString("nama"), 
                res.getString("jabatan"), res.getString("unit_kerja")});
        }
        tablePegawai.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnSearchActionPerformed

