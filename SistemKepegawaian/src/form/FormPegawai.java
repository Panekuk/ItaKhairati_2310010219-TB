    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
       try {
        String sql = "INSERT INTO pegawai (nip, nama, jabatan, unit_kerja) VALUES (?, ?, ?, ?)";
        Connection conn = Koneksi.getKoneksi();
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, txtNip.getText());
        pst.setString(2, txtNama.getText());
        pst.setString(3, txtJabatan.getText());
        pst.setString(4, txtUnit_Kerja.getText());
        pst.execute();
        JOptionPane.showMessageDialog(null, "Penyimpanan Data Berhasil");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    tampilData();
    resetForm();
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
        String sql = "UPDATE pegawai SET nama=?, jabatan=?, unit_kerja=? WHERE nip=?";
        Connection conn = Koneksi.getKoneksi();
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, txtNama.getText());
        pst.setString(2, txtJabatan.getText());
        pst.setString(3, txtUnit_Kerja.getText());
        pst.setString(4, txtNip.getText());
        pst.execute();
        JOptionPane.showMessageDialog(null, "Data Berhasil Diubah");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Perubahan Data Gagal " + e.getMessage());
    }
    tampilData();
    resetForm();
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       int jawab = JOptionPane.showConfirmDialog(null, "Hapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
    if(jawab == JOptionPane.YES_OPTION){
        try {
            String sql = "DELETE FROM pegawai WHERE nip=?";
            Connection conn = Koneksi.getKoneksi();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtNip.getText());
            pst.execute();
            JOptionPane.showMessageDialog(null, "Data Berhasil Dihapus");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        tampilData();
        resetForm();
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

