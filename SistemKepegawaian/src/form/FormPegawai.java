    // Fungsi untuk menampilkan data dari MySQL ke JTable
    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("No");
        model.addColumn("NIP");
        model.addColumn("Nama");
        model.addColumn("Jabatan");
        model.addColumn("Unit Kerja");
    
    try {
        int no = 1;
        String sql = "SELECT * FROM pegawai";
        Connection conn = Koneksi.getKoneksi();
        Statement stm = conn.createStatement();
        ResultSet res = stm.executeQuery(sql);
        while(res.next()){
            model.addRow(new Object[]{no++, res.getString("nip"), 
                res.getString("nama"), res.getString("jabatan"), res.getString("unit_kerja")});
        }
        tablePegawai.setModel(model);
    } catch (Exception e) {
        System.out.println("Error : " + e.getMessage());
    }
}
